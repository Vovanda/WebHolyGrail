import type { MediaRendition } from '@/lib/media';

/**
 * Кадр в ленте страницы.
 *
 * @remarks
 * Собирается из разметки: кубик картинки помечает себя и кладёт рядом всё,
 * что нужно для показа крупно. В сеть за этим лента не ходит - иначе открытие
 * снимка ждало бы ответа сервера.
 */
export interface Shot {
  /** Адрес, который показывается, если браузер не разбирает набор. */
  readonly src: string;
  /** Набор вариантов: из него выбирает экран зрителя. */
  readonly set: readonly MediaRendition[];
  /** Сам файл: открывается кнопкой в отдельной вкладке. */
  readonly file: string;
  /** Размытая заготовка: видна, пока крупный кадр идёт по сети. */
  readonly blur: string;
  /** Что написано вместо картинки - для тех, кто её не видит. */
  readonly alt: string;
  /** Заголовок под кадром. */
  readonly title: string;
  /** Пояснение под заголовком. Длинное сворачивается. */
  readonly note: string;
  /** Пропорции кадра: по ним считается место для кнопок. */
  readonly width: number;
  readonly height: number;
}
