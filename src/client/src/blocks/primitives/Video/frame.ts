/**
 * Вид рамки в том виде, в каком его принимают оба слоя управления.
 *
 * @remarks
 * Слой на vidstack ждёт объект вида вместе с местом под свои CSS-переменные:
 * обычный `CSSProperties` этому месту не подходит, у него нет индекса по
 * `--*`. Тип с этим индексом принимают оба, поэтому он и возвращается.
 */
export type FrameStyle = {
  readonly aspectRatio: string;
  readonly maxHeight: string;
  readonly width: string;
  readonly marginInline: string;
} & Record<`--${string}`, string | number | undefined>;

/**
 * Предел высоты кадра.
 *
 * @remarks
 * Вертикальная запись во всю ширину колонки не влезает в экран: 9/16 при
 * ширине 1440 даёт 2500 px высоты, и зритель видит середину кадра, а не запись.
 * Потолок держит её в пределах экрана, как в Shorts и Reels: кадр высокий, но
 * целиком.
 *
 * Значение живёт токеном, как потолок одиночного снимка: габариты кадра -
 * правило показа, и меняются они правкой стилей, а не релизом.
 */
export const FRAME_MAX_HEIGHT = 'var(--video-frame-max-h)';

/**
 * Рамка кадра под форму записи.
 *
 * @remarks
 * Форма приходит строкой `ширина/высота` - её одинаково понимают CSS и слой на
 * vidstack, а десятичную дробь второй не разбирает.
 *
 * Ширина выводится из потолка высоты, а не задаётся колонкой, и `min()` берёт
 * меньшее из двух: пока место шире потолка, кадр занимает место целиком; когда
 * потолок меньше - сужается и он, по своей пропорции. Отдельной ветки для
 * горизонтальных записей нет: на невысоком окне или узкой колонке они упираются
 * в потолок так же, как вертикальные.
 *
 * `marginInline` нужен потому, что суженный кадр иначе прилипает к левому краю
 * места, и поля вокруг него оказываются неравными.
 */
export function frameStyle(ratio: string): FrameStyle {
  return {
    aspectRatio: ratio,
    maxHeight: FRAME_MAX_HEIGHT,
    width: `min(100%, calc(${FRAME_MAX_HEIGHT} * ${ratio}))`,
    marginInline: 'auto',
  };
}
