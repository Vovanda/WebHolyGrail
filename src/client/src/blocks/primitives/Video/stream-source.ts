/**
 * Нарезка это или отдельный файл.
 *
 * @remarks
 * Отличаются они только адресом: у нарезки это манифест - либо файл `.m3u8`
 * в хранилище, либо дверь сайта, за которой он лежит (R15). Всё остальное -
 * загруженный целиком файл, и браузер играет его сам.
 *
 * Проверка отдельно от подключения потока: подключение тянет за собой
 * библиотеку разбора, а спросить «что за источник» нужно до того, как решено
 * её грузить.
 */
const STREAM = /\.m3u8(?:$|[?#])|\/video\/manifest(?:\/|$)/;

export function isStream(src: string): boolean {
  return STREAM.test(src);
}
