/**
 * Адрес CMS, к которому сайт идёт за данными и файлами.
 *
 * @remarks
 * Разный у стенда и у рабочего сайта, поэтому берётся из окружения: в докере
 * это `http://cms:3001`, на стенде без него - `http://localhost:3001`.
 * Косая черта в конце срезается, чтобы склейка с путём не давала двух подряд.
 */
// Обращение через точку: только его Next подставляет в сборку браузера.
export const CMS_URL = (process.env.NEXT_PUBLIC_CMS_URL || 'http://localhost:3001').replace(
  /\/$/,
  '',
);

/**
 * Абсолютный адрес файла CMS.
 *
 * @remarks
 * Файл приходит то полным адресом раздачи, то путём от корня CMS - когда файлы
 * держит она сама. Браузер на адресе сайта до CMS по такому пути не дойдёт,
 * поэтому путь клеится к её адресу.
 */
export function absoluteUrl(url: string): string {
  if (/^https?:\/\//i.test(url)) return url;
  return `${CMS_URL}${url.startsWith('/') ? '' : '/'}${url}`;
}
