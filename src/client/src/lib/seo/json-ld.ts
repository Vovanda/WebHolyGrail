/**
 * Текст для `<script type="application/ld+json">`.
 *
 * @remarks
 * Внутри script браузер ищет `</script>` в сыром тексте, не разбирая JSON:
 * имя специалиста или название видео с этой строкой закрыло бы тег, и
 * остаток ушёл бы в страницу разметкой. Специалист правит свой профиль сам,
 * так что строка приходит не только от редактора.
 *
 * `<` заменяется кодом символа - так делает документация Next
 * (guides/json-ld). Для разбора JSON это тот же символ.
 */
export function jsonLd(value: unknown): string {
  return JSON.stringify(value).replace(/</g, '\\u003c');
}
