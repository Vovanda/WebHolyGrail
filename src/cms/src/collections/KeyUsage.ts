import type { CollectionConfig } from 'payload';

/**
 * KeyUsage — сколько ключей зритель уже взял и какие именно.
 *
 * @remarks
 * Счёт лежит в базе, а не в памяти процесса: при выкладке рядом работают два
 * цвета на одной базе, и память у каждого своя. Со счётом в памяти смена цвета
 * возвращала выкачивающему полный запас, а выкачивание как раз и растянуто
 * во времени - ровно на такие промежутки.
 *
 * Служебная запись, а не содержимое сайта: в админке её не показываем и снаружи
 * не отдаём. Живёт она недолго - строка на идентичность, и та переписывается.
 */
export const KeyUsage: CollectionConfig = {
  slug: 'key-usage',
  labels: { singular: 'Счёт ключей', plural: 'Счёт ключей' },
  /*
    Блокировка правок здесь не нужна: строку никто не открывает в админке,
    её переписывает сама выдача. А с блокировкой Payload на каждую запись
    ходит в служебную таблицу связей, где для этой коллекции нет колонки.
  */
  lockDocuments: false,
  admin: {
    useAsTitle: 'viewer',
    hidden: true,
    group: 'Медиа',
    description: 'Служебное: сколько ключей взято с одного идентичности.',
  },
  fields: [
    {
      name: 'viewer',
      label: 'Идентичность',
      type: 'text',
      required: true,
      index: true,
      unique: true,
    },
    {
      name: 'keysLeft',
      label: 'Остаток запаса',
      type: 'number',
      required: true,
    },
    {
      name: 'countedAt',
      label: 'Когда считали',
      type: 'number',
      required: true,
    },
    {
      /**
       * Уже выданные ключи: `запись:период` → когда выдан.
       *
       * @remarks
       * По ним повтор отличается от нового ключа: страница с тремя плеерами
       * одной записи просит один и тот же, а выкачивание идёт по разным.
       */
      name: 'issuedKeys',
      label: 'Выданные ключи',
      type: 'json',
    },
  ],
  access: {
    // Счёт ключей - внутренняя кухня выдачи: снаружи он не читается и не
    // правится вовсе, а сама выдача ходит мимо прав.
    read: () => false,
    create: () => false,
    update: () => false,
    delete: () => false,
  },
};
