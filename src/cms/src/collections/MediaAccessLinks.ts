import type { CollectionConfig } from 'payload';

import { generateLinkToken } from '../lib/video/link-token';

/**
 * AccessLinks — ссылки-приглашения на подборку или запись.
 *
 * @remarks
 * Ссылка и код доступа решают разные задачи, и потому живут врозь. Код адресный:
 * его выдают человеку, диктуют по телефону и переписывают из смс — значит он
 * короткий и без похожих начертаний. Ссылка не про «кому», а про «всякому, у кого
 * есть адрес»: её присылают целиком, руками не набирают, и адрес у неё длинный,
 * чтобы чужое приглашение нельзя было подобрать.
 *
 * Пока обе сущности лежали одной коллекцией, ссылку выдавали тем же коротким
 * кодом — то есть перебором подбиралось всё, что кому-то отправлено.
 *
 * Способ выдачи права, а не отдельный вид доступа: сработав, ссылка превращается
 * в обычное право «зритель × подборка или запись» — то же самое, что делает код.
 *
 * Срок обязателен. Ссылка расходится по чатам и живёт там дольше, чем помнит
 * о ней выдавший; бессрочная означает, что подборка открыта навсегда всякому,
 * кто однажды получил адрес. Отзыв — на случай, когда ждать срока не хочется.
 */
export const MediaAccessLinks: CollectionConfig = {
  slug: 'media-access-links',
  labels: { singular: 'Ссылка-приглашение', plural: 'Ссылки-приглашения' },
  admin: {
    useAsTitle: 'label',
    defaultColumns: ['label', 'access', 'expiresAt', 'revoked', 'usedCount'],
    group: 'Медиа',
    description:
      'Открывают подборку или запись всякому, у кого есть адрес. В отличие от кодов доступа их не диктуют, а присылают.',
  },
  fields: [
    {
      /**
       * Пометка для того, кто выдаёт.
       *
       * @remarks
       * Стоит первой и служит именем записи: адрес ссылки нечитаем, и список
       * из двух десятков одинаковых наборов символов бесполезен. По пометке
       * владелец вспоминает, кому и зачем отправлял.
       */
      name: 'label',
      label: 'Пометка',
      type: 'text',
      admin: { description: 'Кому и зачем выдана. Видно только в админке.' },
    },
    {
      name: 'token',
      label: 'Адрес',
      type: 'text',
      unique: true,
      index: true,
      admin: {
        readOnly: true,
        description: 'Заполняется сам. Длинный и неудобный для диктовки — на то это и ссылка.',
      },
    },
    {
      /**
       * От какого доступа выдана ссылка.
       *
       * @remarks
       * Как право и код, ссылка ведёт к доступу, а не к материалу напрямую:
       * что откроется, знает сам доступ, и меняется его состав - меняется
       * открытое по ссылке.
       */
      name: 'access',
      label: 'Доступ',
      type: 'relationship',
      relationTo: 'media-accesses',
      required: true,
      index: true,
    },
    {
      /**
       * Отзыв одним действием.
       *
       * @remarks
       * Галка, а не удаление записи: выданные по ссылке права остаются
       * привязанными к ней, и по отозванной видно, что и когда закрыли.
       */
      name: 'revoked',
      label: 'Отозвана',
      type: 'checkbox',
      defaultValue: false,
      admin: { description: 'Перестаёт открывать сразу. Выданные ранее права снимаются отдельно.' },
    },
    {
      name: 'expiresAt',
      label: 'Действует до',
      type: 'date',
      required: true,
      admin: {
        description: 'Обязательно: ссылка живёт в чатах дольше, чем о ней помнят.',
        date: { pickerAppearance: 'dayOnly', displayFormat: 'd MMMM yyyy' },
      },
    },
    {
      name: 'maxUses',
      label: 'Сколько раз сработает',
      type: 'number',
      min: 1,
      admin: { description: 'Пусто — без ограничения, пока не кончился срок.' },
    },
    {
      name: 'usedCount',
      label: 'Уже сработала раз',
      type: 'number',
      defaultValue: 0,
      admin: { readOnly: true },
    },
    {
      /**
       * Сколько живёт доступ, выданный этой ссылкой.
       *
       * @remarks
       * Отличается от срока самой ссылки: ссылка может работать месяц, а каждый
       * выданный по ней доступ — неделю.
       */
      name: 'grantDays',
      label: 'На сколько дней открывает',
      type: 'number',
      min: 1,
      admin: { description: 'Пусто — навсегда.' },
    },
  ],
  hooks: {
    beforeValidate: [
      ({ data }) => {
        if (!data) return data;

        // Адрес не задаётся руками: короткий или осмысленный подбирается перебором,
        // а вводить его всё равно некому - ссылку открывают нажатием.
        if (!data['token']) data['token'] = generateLinkToken();

        // Срок обязателен, поэтому у не указавшего он становится месячным,
        // а не бессрочным: молчание не должно означать «навсегда».
        if (!data['expiresAt']) {
          const month = new Date();
          month.setMonth(month.getMonth() + 1);
          data['expiresAt'] = month.toISOString();
        }
        return data;
      },
    ],
  },
  access: {
    // Список ссылок - список ключей от закрытого, читать его может только тот,
    // кто их выдаёт.
    read: ({ req: { user } }) => Boolean(user),
    create: ({ req: { user } }) => Boolean(user),
    update: ({ req: { user } }) => Boolean(user),
    delete: ({ req: { user } }) => Boolean(user),
  },
};
