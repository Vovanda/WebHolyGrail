import type { CollectionConfig } from 'payload';

/**
 * Право - личная запись «кому открыт доступ и на каких условиях».
 *
 * @remarks
 * Личное и со своими условиями: своя дата истечения, своё число просмотров,
 * чем приобретено. Один купил бессрочно, другой вошёл по недельному промо -
 * и это один и тот же доступ, а не два.
 *
 * Живость вычисляется из условий, а не хранится флагом: иначе истёкшее ждало
 * бы, пока его кто-нибудь погасит, и до тех пор пускало бы. Срок считается
 * по более раннему из двух - личного и общей отсечки доступа.
 *
 * Способ выдачи модели безразличен — оплата, подарок, код или рука
 * владельца. Когда появится платёжка, она встанет сюда же и ни плеер,
 * ни нарезка об этом не узнают.
 */
export const MediaAccessRights: CollectionConfig = {
  slug: 'media-access-rights',
  labels: { singular: 'Право', plural: 'Права' },
  admin: {
    useAsTitle: 'id',
    defaultColumns: ['viewer', 'visitorMarker', 'access', 'source', 'expiresAt'],
    group: 'Медиа',
    description: 'Кому открыт доступ. Выдаётся оплатой, кодом или решением владельца.',
  },
  fields: [
    {
      name: 'viewer',
      label: 'Учётная запись',
      type: 'relationship',
      relationTo: 'users',
      index: true,
      admin: {
        description: 'Пусто, пока доступ выдан на телефон или почту и человек ещё не входил.',
      },
    },
    {
      /**
       * Телефон, на который выдан доступ.
       *
       * @remarks
       * Номер и есть идентичность: учётная запись необязательна. С нового
       * устройства человек вводит свой телефон, получает код и возвращает
       * доступ сам, не обращаясь к продавцу.
       *
       * Хранится в едином виде — только цифры: человек пишет номер как
       * придётся, и без приведения тот же телефон не совпал бы сам с собой.
       */
      name: 'phone',
      label: 'Телефон',
      type: 'text',
      index: true,
    },
    {
      name: 'email',
      label: 'Почта',
      type: 'email',
      index: true,
      admin: { description: 'Второй способ идентичности, если кода прислали письмом.' },
    },
    {
      /**
       * Маркер посетителя - чем узнаётся зритель без учётной записи.
       *
       * @remarks
       * Сервер выдаёт его браузеру при первой встрече и кладёт в токен, поэтому
       * записать право есть куда всегда. Право по коду существует записью
       * и у того, кто учётной записи не заводил: пока оно жило в токене, снять
       * его было нельзя - сервер о нём не знал.
       *
       * Личности за маркером нет: это не имя человека и не ссылка, а имя,
       * под которым к нему приписано открытое.
       */
      name: 'visitorMarker',
      label: 'Маркер посетителя',
      type: 'text',
      index: true,
      admin: {
        description: 'Метка браузера, которому выдано право. Пусто, если право на учётную запись.',
        readOnly: true,
      },
    },
    {
      /**
       * На какой доступ выдано право.
       *
       * @remarks
       * Право лежит на доступе, а не на каждом материале внутри, и вниз
       * распространяется при проверке: доступ, в который входит подборка,
       * открывает всё, что в ней лежит сейчас. Состав подборки поменялся -
       * право поменялось само, догонять нечего.
       *
       * Отсюда же берётся отзыв разом: отсечка доступа закрывает материал
       * у всех держателей сразу, сколько бы прав ни было выдано.
       */
      name: 'access',
      label: 'Доступ',
      type: 'relationship',
      relationTo: 'media-accesses',
      required: true,
      index: true,
    },
    {
      name: 'source',
      label: 'Чем выдан',
      type: 'select',
      defaultValue: 'manual',
      options: [
        { label: 'Вручную', value: 'manual' },
        { label: 'Оплата', value: 'payment' },
        { label: 'Ссылка-приглашение', value: 'invite' },
        { label: 'Код доступа', value: 'promo' },
      ],
      admin: { description: 'Нужно, чтобы понимать, откуда пришёл доступ, когда придёт биллинг.' },
    },
    {
      /**
       * До какой даты действует.
       *
       * @remarks
       * Пусто — бессрочно. Срок нужен подаркам и акциям: «дать посмотреть
       * курс на неделю» без него превращается в «отдать курс насовсем».
       */
      name: 'expiresAt',
      label: 'Действует до',
      type: 'date',
      admin: {
        description: 'Пусто — навсегда.',
        date: { pickerAppearance: 'dayOnly', displayFormat: 'd MMMM yyyy' },
      },
    },
    {
      /**
       * Сколько просмотров осталось у этого права.
       *
       * @remarks
       * Пусто в пределе - без ограничения. Условие личное: у одного доступ
       * бессрочный, у другого разовый показ, и это один и тот же доступ.
       */
      name: 'maxViews',
      label: 'Сколько просмотров',
      type: 'number',
      min: 1,
      admin: { description: 'Пусто — без ограничения.' },
    },
    {
      name: 'views',
      label: 'Просмотрено',
      type: 'number',
      defaultValue: 0,
      admin: { description: 'Считается само.', readOnly: true },
    },
    {
      name: 'note',
      label: 'Пометка',
      type: 'text',
      admin: { description: 'Для себя: за что выдано право.' },
    },
  ],
  access: {
    // Свои права видит сам зритель, чужие — администратор.
    // Иначе список покупателей чужого доступа читался бы кем угодно.
    read: ({ req: { user } }) => {
      if (!user) return false;
      if (user.role === 'admin') return true;
      return { viewer: { equals: user.id } };
    },
    create: ({ req: { user } }) => Boolean(user),
    update: ({ req: { user } }) => user?.role === 'admin',
    delete: ({ req: { user } }) => user?.role === 'admin',
  },
};
