import type { CollectionConfig } from 'payload';

import { generateAccessCode, normalizeAccessCode } from '../lib/video/access-code';
import { codeExpiry, codeRules, type VideoCodeSettings } from '../lib/video/code-rules';

/**
 * AccessCodes — короткие коды, открывающие подборку или запись.
 *
 * @remarks
 * Способ выдачи права, а не отдельный вид доступа: код срабатывает и
 * превращается в обычное право «зритель × подборка или запись». Когда придёт платёжка,
 * она встанет рядом и будет создавать такие же права.
 *
 * Код диктуют по телефону и переписывают из смс — отсюда и короткая длина,
 * и алфавит без похожих начертаний. Ссылки-приглашения живут отдельной
 * коллекцией: их присылают целиком, руками не набирают, и адрес у них длинный,
 * чтобы чужое приглашение нельзя было подобрать перебором. Пока обе сущности
 * лежали здесь, ссылку выдавали тем же шестизначным кодом.
 *
 * Ключевая настройка — нужен ли вход. Она про то, чем доступ держится: с входом
 * за учётной записью, без входа за идентичностью браузера. Отозвать можно и то,
 * и другое — право в обоих случаях лежит записью, — но учётная запись остаётся
 * с человеком, а идентичность живёт до чистки данных, и с нового устройства доступ
 * придётся возвращать кодом заново.
 *
 * Второе отличие важнее: разошедшийся по чатам код без входа откроет плейлист
 * каждому, кто его увидел, и прав станет столько же, сколько людей. Поэтому
 * у такого кода обязательны срок и предел срабатываний.
 */
export const AccessCodes: CollectionConfig = {
  slug: 'access-codes',
  labels: { singular: 'Код доступа к материалу', plural: 'Коды доступа к материалам' },
  admin: {
    useAsTitle: 'code',
    defaultColumns: ['code', 'resource', 'usedCount', 'expiresAt'],
    group: 'Медиа',
    description:
      'Короткий код, который диктуют и переписывают. Превращается в обычное право доступа. Ссылки-приглашения живут отдельно — их присылают целиком.',
  },
  fields: [
    {
      name: 'code',
      label: 'Код',
      type: 'text',
      unique: true,
      index: true,
      admin: {
        description: 'Заполнится сам, если оставить пустым. Можно задать своё слово для рекламы.',
      },
    },
    {
      /**
       * На что открывает — на подборку или на саму запись.
       *
       * @remarks
       * Устроено так же, как у права и у ссылки-приглашения: код на одиночное
       * видео нужен ничуть не реже, чем на подборку, а раньше выдать его было
       * нечем — связь вела только к подборке.
       */
      name: 'resource',
      label: 'На что',
      type: 'relationship',
      relationTo: ['playlists', 'media'],
      index: true,
      admin: {
        description: 'Подборка целиком или одна запись.',
      },
    },
    {
      /**
       * @deprecated Заменено полем «На что»: оно умеет и подборку, и запись.
       *
       * @remarks
       * Остаётся ради выданных прежде кодов - у них заполнено только оно,
       * и погашение читает его, когда «На что» пустует. Убрать можно будет,
       * когда все коды переедут; пока удаление означало бы, что старые коды
       * перестают открывать (R10).
       */
      name: 'playlist',
      label: 'Плейлист (устаревшее)',
      type: 'relationship',
      relationTo: 'playlists',
      admin: {
        description: 'Прежнее поле. У новых кодов заполняется «На что».',
        condition: (data) => Boolean(data?.playlist),
      },
    },
    {
      name: 'maxUses',
      label: 'Сколько раз сработает',
      type: 'number',
      min: 1,
      admin: {
        description:
          'Пусто — сработает пятьдесят раз. Код открывает запись предъявителю, поэтому счётчик у него есть всегда.',
      },
    },
    {
      name: 'usedCount',
      label: 'Уже сработал раз',
      type: 'number',
      defaultValue: 0,
      admin: { readOnly: true },
    },
    {
      name: 'expiresAt',
      label: 'Действует до',
      type: 'date',
      admin: {
        description:
          'Обязательно. Не указан — месяц со дня выдачи: бессрочный код остаётся в переписке дольше, чем о нём помнят.',
        date: { pickerAppearance: 'dayOnly', displayFormat: 'd MMMM yyyy' },
      },
    },
    {
      /**
       * Сколько живёт доступ, выданный этим кодом.
       *
       * @remarks
       * Отличается от срока самого кода: код может работать месяц, а каждый
       * выданный по нему доступ — неделю. Так устроены подарки «посмотреть
       * до конца недели».
       */
      name: 'grantDays',
      label: 'На сколько дней открывает',
      type: 'number',
      min: 1,
      /*
        Умолчание берётся из настроек сайта, а не стоит числом здесь: срок
        доступа владелец правит сам. Поле остаётся перекрытием - стёртое
        по-прежнему означает «навсегда».
      */
      defaultValue: async ({ req }) => {
        const settings = (await req.payload.findGlobal({
          slug: 'site-settings',
          depth: 0,
        })) as { video?: VideoCodeSettings };
        return codeRules(settings.video).grantDays;
      },
      admin: { description: 'Пусто — навсегда. Подставляется срок из настроек сайта.' },
    },
    {
      /**
       * Срок доступа в минутах.
       *
       * @remarks
       * Для показа и вебинара сутки - слишком много: доступ нужен на время
       * самого события. Заданные минуты главнее дней, поэтому поле пустует
       * у обычного кода и заполняется там, где счёт идёт на часы.
       */
      name: 'grantMinutes',
      label: 'На сколько минут открывает',
      type: 'number',
      min: 1,
      admin: {
        description:
          'Для показов и коротких демонстраций. Заполнено — счёт идёт по минутам, а не по дням.',
      },
    },
  ],
  hooks: {
    beforeValidate: [
      async ({ data, req }) => {
        if (!data) return data;

        // Длина кода и оба срока живут в настройках сайта: владелец правит их
        // без разработчика, поэтому чисел здесь нет - только правила по ним.
        const settings = (await req.payload.findGlobal({
          slug: 'site-settings',
          depth: 0,
        })) as { video?: VideoCodeSettings };
        const rules = codeRules(settings.video);
        /*
          Код доступа диктуют по телефону и переписывают из смс, поэтому и рождается
          он в алфавите для диктовки, и своё слово владельца приводится к нему же.

          Иначе введённое расходится с записанным: адресная машинка выдаёт оба
          регистра, а введённый код проходит нормализацию - заглавные, «O» в ноль,
          «I» и «L» в единицу. Совпасть они могли только случайно, и заведённый
          в админке код не гасился вовсе.
        */
        data['code'] = data['code']
          ? normalizeAccessCode(String(data['code']))
          : generateAccessCode(rules.length);

        /*
          Срок обязателен у любого кода, а не только у работающего без входа:
          бессрочный остаётся в переписке и открывает плейлист спустя годы,
          когда выдавший о нём давно забыл. Молчание не должно означать
          «навсегда», поэтому не указанный срок берётся из настроек сайта.
        */
        if (!data['expiresAt']) {
          data['expiresAt'] = codeExpiry(rules, new Date());
        }

        /*
          Код открывает запись предъявителю, поэтому число срабатываний у него
          есть всегда: разойдясь по чатам, он иначе открыл бы её каждому, кто
          его увидел. Отозвать выданное можно - право лежит записью, - но
          снимать их придётся по одному на каждого.
        */
        if (!data['maxUses']) {
          data['maxUses'] = 50;
        }

        /*
          Заполнено прежнее поле, а новое пустует - переносим. Так код, заведённый
          старым способом (в том числе чужим кодом, который ещё шлёт `playlist`),
          сразу получает связь того вида, который читает погашение.
        */
        if (!data['resource'] && data['playlist']) {
          data['resource'] = { relationTo: 'playlists', value: data['playlist'] };
        }
        return data;
      },
    ],
  },
  access: {
    // Читать коды может только тот, кто их выдаёт: список кодов — это список
    // ключей от закрытого.
    read: ({ req: { user } }) => Boolean(user),
    create: ({ req: { user } }) => Boolean(user),
    update: ({ req: { user } }) => Boolean(user),
    delete: ({ req: { user } }) => Boolean(user),
  },
};
