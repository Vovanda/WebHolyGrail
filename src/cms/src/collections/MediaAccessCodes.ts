import type { CollectionConfig } from 'payload';

import { generateAccessCode, normalizeAccessCode } from '../lib/video/access-code';
import { codeExpiry, codeRules, type VideoCodeSettings } from '../lib/video/code-rules';

/**
 * Код - одноразовый пароль к доступу: кто его получил, тот получил и право.
 *
 * @remarks
 * Способ выдачи, а не вид доступа: сработав, код заводит обычное право на тот
 * доступ, от которого напечатан, и кончается. Когда придёт платёжка, она
 * встанет рядом и будет заводить такие же права.
 *
 * Вид у кода два, и различаются они только тем, как попадают к человеку.
 * Диктуемый короткий, в алфавите без похожих начертаний: его читают вслух
 * и переписывают из сообщения. Присылаемый длинный и машинный - его не
 * набирают руками, а перешлют дальше, чем помнят о его существовании,
 * поэтому подобрать его перебором нельзя.
 *
 * Сдерживают код срок и предел срабатываний: разойдясь по чатам, он иначе
 * открыл бы доступ каждому, кто его увидел. Отозвать выданное можно и после -
 * каждое право лежит записью.
 */
export const MediaAccessCodes: CollectionConfig = {
  slug: 'media-access-codes',
  labels: { singular: 'Код доступа', plural: 'Коды доступа' },
  /*
    Сверху действующие. Коды живут пять минут и копятся десятками за день:
    в списке по порядку создания живой не найти, а ищут именно его - чтобы
    продиктовать или отозвать.

    Порядок по сроку и решает: у живого он в будущем, у отработавшего в прошлом.
    Отработавшие остаются ниже - это след выдачи, по нему видно, кому и когда
    открывали, и находится он обычным фильтром по сроку.

    Не жёстким фильтром: тот прячет записи и в списке, и в выборе связей, снять
    его из админки нельзя, и след выдачи пропал бы совсем.
  */
  defaultSort: '-expiresAt',
  admin: {
    useAsTitle: 'code',
    defaultColumns: ['code', 'access', 'usedCount', 'expiresAt'],
    group: 'Медиа',
    description:
      'Короткий код, который диктуют и переписывают. Превращается в обычное право доступа. Ссылки-приглашения живут отдельно — их присылают целиком.',
  },
  fields: [
    {
      name: 'code',
      label: 'Код',
      type: 'text',
      unique: true,
      index: true,
      admin: {
        description: 'Заполнится сам, если оставить пустым. Можно задать своё слово для рекламы.',
      },
    },
    {
      /**
       * На что открывает — на подборку или на саму запись.
       *
       * От какого доступа напечатан код.
       *
       * @remarks
       * Код - билет к доступу, а не запись о праве: погашённый, он заводит
       * право на этот доступ и кончается. Что именно откроется, решает доступ,
       * а не сам код.
       */
      name: 'access',
      label: 'Доступ',
      type: 'relationship',
      relationTo: 'media-accesses',
      index: true,
      admin: { description: 'Что откроет код. Состав задаётся в самом доступе.' },
    },
    {
      name: 'label',
      label: 'Пометка',
      type: 'text',
      admin: { description: 'Кому и зачем выдан. Видно только в админке.' },
    },
    {
      /**
       * Отзыв одним действием.
       *
       * @remarks
       * Галка, а не удаление записи: выданные по коду права остаются
       * привязанными к нему, и по отозванному видно, что и когда закрыли.
       */
      name: 'revoked',
      label: 'Отозван',
      type: 'checkbox',
      defaultValue: false,
      admin: { description: 'Перестаёт открывать сразу. Выданные ранее права снимаются отдельно.' },
    },
    {
      name: 'maxUses',
      label: 'Сколько раз сработает',
      type: 'number',
      min: 1,
      defaultValue: 1,
      admin: {
        description: 'Больше одного ставят, когда код раздают нескольким людям.',
      },
    },
    {
      name: 'usedCount',
      label: 'Уже сработал раз',
      type: 'number',
      defaultValue: 0,
      admin: { readOnly: true },
    },
    {
      name: 'expiresAt',
      label: 'Действует до',
      type: 'date',
      admin: {
        description:
          'Не указан — пять минут со дня выдачи, как у любого одноразового пароля. Срок берётся из настроек сайта.',
        date: { pickerAppearance: 'dayOnly', displayFormat: 'd MMMM yyyy' },
      },
    },
    {
      /**
       * Сколько живёт доступ, выданный этим кодом.
       *
       * @remarks
       * Отличается от срока самого кода: код может работать месяц, а каждый
       * выданный по нему доступ — неделю. Так устроены подарки «посмотреть
       * до конца недели».
       */
      name: 'grantDays',
      label: 'На сколько дней открывает',
      type: 'number',
      min: 1,
      /*
        Умолчание берётся из настроек сайта, а не стоит числом здесь: срок
        доступа владелец правит сам. Поле остаётся перекрытием - стёртое
        по-прежнему означает «навсегда».
      */
      defaultValue: async ({ req }) => {
        const settings = (await req.payload.findGlobal({
          slug: 'site-settings',
          depth: 0,
        })) as { video?: VideoCodeSettings };
        return codeRules(settings.video).grantDays;
      },
      admin: { description: 'Пусто — навсегда. Подставляется срок из настроек сайта.' },
    },
    {
      /**
       * Срок доступа в минутах.
       *
       * @remarks
       * Для показа и вебинара сутки - слишком много: доступ нужен на время
       * самого события. Заданные минуты главнее дней, поэтому поле пустует
       * у обычного кода и заполняется там, где счёт идёт на часы.
       */
      name: 'grantMinutes',
      label: 'На сколько минут открывает',
      type: 'number',
      min: 1,
      admin: {
        description:
          'Для показов и коротких демонстраций. Заполнено — счёт идёт по минутам, а не по дням.',
      },
    },
  ],
  hooks: {
    beforeValidate: [
      async ({ data, req, operation }) => {
        if (!data) return data;

        /*
          Правки существующего кода - смена срока, отзыв, счётчик срабатываний -
          значения не касаются: перегенерировать его на месте значит оборвать
          все выданные копии.
        */
        if (operation !== 'create') return data;

        // Длина кода и оба срока живут в настройках сайта: владелец правит их
        // без разработчика, поэтому чисел здесь нет - только правила по ним.
        const settings = (await req.payload.findGlobal({
          slug: 'site-settings',
          depth: 0,
        })) as { video?: VideoCodeSettings };
        const rules = codeRules(settings.video);
        /*
          Код доступа диктуют по телефону и переписывают из смс, поэтому и рождается
          он в алфавите для диктовки, и своё слово владельца приводится к нему же.

          Иначе введённое расходится с записанным: адресная машинка выдаёт оба
          регистра, а введённый код проходит нормализацию - заглавные, «O» в ноль,
          «I» и «L» в единицу. Совпасть они могли только случайно, и заведённый
          в админке код не гасился вовсе.
        */
        data['code'] = data['code']
          ? normalizeAccessCode(String(data['code']))
          : generateAccessCode(rules.length);

        /*
          Срок обязателен у любого кода, а не только у работающего без входа:
          бессрочный остаётся в переписке и открывает плейлист спустя годы,
          когда выдавший о нём давно забыл. Молчание не должно означать
          «навсегда», поэтому не указанный срок берётся из настроек сайта.
        */
        if (!data['expiresAt']) {
          data['expiresAt'] = codeExpiry(rules, new Date());
        }

        // Код одноразовый: это пароль на один вход. Больше срабатываний ставят
        // руками, когда один код раздают нескольким людям.
        if (!data['maxUses']) {
          data['maxUses'] = 1;
        }
        return data;
      },
    ],
  },
  access: {
    // Читать коды может только тот, кто их выдаёт: список кодов — это список
    // ключей от закрытого.
    read: ({ req: { user } }) => Boolean(user),
    create: ({ req: { user } }) => Boolean(user),
    update: ({ req: { user } }) => Boolean(user),
    delete: ({ req: { user } }) => Boolean(user),
  },
};
