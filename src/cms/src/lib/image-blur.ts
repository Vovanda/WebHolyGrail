import sharp from 'sharp';

/**
 * Размытая заготовка кадра: то, что видно, пока идёт сам снимок.
 *
 * @remarks
 * Снимок на медленной сети приходит секундами, и всё это время на его месте
 * пустое поле: страница выглядит дырявой, а высота ещё и прыгает, когда кадр
 * наконец встал. Заготовка занимает его место сразу и показывает, что там
 * будет - цвета, светлые и тёмные пятна, общий строй кадра.
 *
 * Она хранится строкой в самой записи, а не отдельным файлом: своего запроса
 * у неё нет, она приходит вместе с данными страницы и рисуется в тот же миг,
 * что и разметка. Поэтому важен размер - несколько сотен байт: строка едет
 * в каждом ответе, где есть эта картинка.
 *
 * Сама заготовка не размыта и не пережата - это просто очень мелкая картинка.
 * Размывает её показ, отдельным слоем: так пятна выходят мягкими, а не
 * ступенчатыми, как при растягивании сжатого до каши кадра.
 *
 * Шестьдесят четыре точки - тот размер, на котором предметы ещё узнаются:
 * в тридцать две синяя бочка занимает два пикселя и читается пятном. Строка
 * при этом остаётся в районе восьмисот байт.
 */
const WIDTH = 64;

/** Выше этого заготовка не хранится: строка дороже пользы от неё. */
const MAX_BYTES = 2048;

export async function makeBlurData(input: Buffer): Promise<string | null> {
  try {
    const { data, info } = await sharp(input)
      .resize(WIDTH, undefined, { fit: 'inside', withoutEnlargement: true })
      .webp({ quality: 62, alphaQuality: 70, effort: 6, smartSubsample: true })
      .toBuffer({ resolveWithObject: true });

    if (!info.width || data.length > MAX_BYTES) return null;
    return `data:image/webp;base64,${data.toString('base64')}`;
  } catch {
    // Не картинка или битый файл: показ обойдётся без заготовки.
    return null;
  }
}
