import sharp from 'sharp';

/**
 * Тёмная ли картинка: по ней выбирается цвет текста поверх неё.
 *
 * @remarks
 * Обложка бывает любой - ночной кадр и снежное поле требуют разного текста,
 * а угадать по одному варианту нельзя: на светлой белые буквы пропадают.
 *
 * Считается один раз при загрузке файла: тянуть картинку из хранилища на
 * каждый показ страницы было бы дороже самой страницы. В браузере это тоже
 * не посчитать - файлы лежат на чужом домене, и холст с ними не прочитать.
 *
 * Яркость берётся по срединной точке уменьшенной картинки, взвешенно по тому,
 * как глаз воспринимает цвета: зелёный весит больше красного, красный - больше
 * синего.
 */

/** Ниже этой яркости картинка считается тёмной. */
const DARK_THRESHOLD = 0.55;

export async function isDarkImage(input: Buffer): Promise<boolean | null> {
  try {
    const { data } = await sharp(input)
      .resize(1, 1, { fit: 'cover' })
      .removeAlpha()
      .raw()
      .toBuffer({ resolveWithObject: true });

    const [r, g, b] = [data[0] ?? 0, data[1] ?? 0, data[2] ?? 0];
    const luma = (0.2126 * r + 0.7152 * g + 0.0722 * b) / 255;
    return luma < DARK_THRESHOLD;
  } catch {
    // Не картинка или битый файл: цвет текста тогда выбирается по умолчанию.
    return null;
  }
}
