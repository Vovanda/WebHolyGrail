import { hkdfSync } from 'node:crypto';

/**
 * Ключ криптопериода: запись шифруется не одним ключом, а по отрезкам.
 *
 * @remarks
 * Один ключ на всю запись означает, что зритель, получивший его однажды,
 * держит в руках всю запись целиком: доигрывает её после отзыва права и
 * собирает файл из частей, которые раздача отдаёт кому угодно.
 *
 * Поэтому запись делится на криптопериоды по нескольку частей, и у каждой криптопериоды свой
 * ключ. Утёкший ключ отдаёт ровно свою криптопериод, отозванное право перестаёт
 * открывать на ближайшей границе, а собрать запись целиком можно, лишь
 * запросив каждую криптопериод — то есть пройдя её в темпе просмотра.
 *
 * Ключи не хранятся. Они выводятся из секрета записи и номера криптопериода, поэтому
 * нарезка и выдача приходят к одному ключу, ни о чём не договариваясь, а в
 * базе не заводится склад одинаковых по смыслу секретов, растущий с длиной.
 *
 * Вывод односторонний: из ключа криптопериоды не получить ни секрет записи, ни ключ
 * соседнего криптопериода. Благодаря этому секрет записи перестаёт покидать сервер —
 * зритель даже с полным правом видит только ключи тех криптопериодов, до которых дошёл.
 */

/** Длина ключа AES-128, которым ffmpeg шифрует части. */
const KEY_BYTES = 16;

/**
 * Соль вывода.
 *
 * @remarks
 * Постоянная: разделение криптопериодов обеспечивает не она, а номер, который уходит
 * в поле сведений. Соль здесь отделяет это применение секрета от любого
 * другого, если оно однажды появится.
 */
const SALT = 'whg-video-period';

/**
 * Ключ криптопериода из секрета записи.
 *
 * @remarks
 * HKDF на SHA-256: он и разводит один секрет на сколько угодно ключей, и не
 * даёт пройти обратно — ни к секрету, ни к соседям.
 */
export function periodKey(secret: Buffer, period: number): Buffer {
  if (!Number.isInteger(period) || period < 0) {
    throw new Error('Номер криптопериода должен быть целым и неотрицательным.');
  }
  return Buffer.from(hkdfSync('sha256', secret, SALT, `period:${period}`, KEY_BYTES));
}

/** Что отдать плееру: ключ или отказ с причиной. */
export type KeyPick =
  | { readonly ok: true; readonly key: Buffer }
  | { readonly ok: false; readonly reason: 'period-required' | 'period-unexpected' };

/**
 * Ключ по номеру криптопериоды из адреса.
 *
 * @remarks
 * Номер приходит из манифеста, а не считается делением номера части на шаг:
 * границу криптопериоды ставит муксер, и она не совпадает с расчётной. Он перечитывает
 * keyinfo, уже начав очередную часть, поэтому смена приходится на часть позже
 * задуманного, а по ступеням качества может разойтись ещё сильнее. Номер же
 * попадает в манифест ровно там, где ключ сменился на самом деле.
 *
 * У криптопериодовной записи запрос без номера отклоняется, и это не придирка к форме:
 * иначе на такой запрос ушёл бы сам секрет записи — корень, из которого
 * выводятся все её ключи.
 *
 * Записи, нарезанные до появления криптопериодов, помечены пустым шагом. Им отдаётся
 * единственный ключ, как было раньше: перезаливать их нельзя, поэтому этот
 * путь остаётся навсегда (R10).
 */
export function keyForPeriod(secret: Buffer, period: number | null, split: boolean): KeyPick {
  if (split) {
    if (period === null) return { ok: false, reason: 'period-required' };
    return { ok: true, key: periodKey(secret, period) };
  }
  if (period !== null) return { ok: false, reason: 'period-unexpected' };
  return { ok: true, key: secret };
}
