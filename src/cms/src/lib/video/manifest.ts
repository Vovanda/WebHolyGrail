/**
 * Манифест, отданный со своего домена.
 *
 * @remarks
 * В манифесте стоит путь ключа без домена - иначе адрес CMS цементируется
 * в файле навсегда. А относительный путь браузер разрешает от адреса самого
 * манифеста: лежит он в раздаче - туда запрос и уйдёт.
 *
 * Отсюда зеркальная ручка: файл остаётся в хранилище рядом с сегментами,
 * но плеер берёт его с нашего домена, и путь ключа разрешается правильно.
 * Сегменты через нас не идут - ссылки на них переписываются в адрес раздачи.
 *
 * Сам путь ключа здесь не трогается: его пишет нарезка, и знать его форму
 * должно одно место. Второе такое место уже разошлось с первым молча.
 */

/** Строка манифеста, которая указывает на файл, а не на настройку. */
const isReference = (line: string): boolean => line.trim() !== '' && !line.startsWith('#');

export interface RewriteOptions {
  /** Где лежит сам манифест в раздаче: `https://cdn/media/u1/hls/<uuid>/480p`. */
  readonly folder: string;
  /** Свой адрес этой же папки: `/api/video/87/manifest/480p`. */
  readonly own: string;
}

/**
 * Переписывает ссылки на файлы внутри манифеста.
 *
 * @remarks
 * Вложенные манифесты остаются за нами - иначе плеер уйдёт за ними на раздачу,
 * и ключ снова станет разрешаться от чужого домена. Сегменты, наоборот,
 * уводятся на раздачу целиком.
 *
 * Настройки, включая строку ключа, проходят нетронутыми: они начинаются
 * с решётки, а здесь переписываются только ссылки на файлы.
 */
export function rewriteManifest(text: string, { folder, own }: RewriteOptions): string {
  const base = folder.replace(/\/+$/, '');
  const mine = own.replace(/\/+$/, '');

  return text
    .split('\n')
    .map((line) => {
      if (!isReference(line)) return line;

      const target = line.trim();
      // Уже абсолютную ссылку не трогаем: её вписали осознанно.
      if (/^https?:\/\//i.test(target)) return line;

      return target.endsWith('.m3u8') ? `${mine}/${target}` : `${base}/${target}`;
    })
    .join('\n');
}
