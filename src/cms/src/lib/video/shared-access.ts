/**
 * Складчина: сколько человек смотрит под одним доступом.
 *
 * @remarks
 * Пока ключ выдавался один на всю запись, зритель был виден ровно однажды -
 * и десять человек по общему коду ничем не отличались от одного. С ключами
 * по криптопериодам каждый обращается заново раз в минуту, и под одним правом
 * становятся видны отдельные линии: у каждой свой клиент и своё место в записи.
 *
 * Один человек тоже даёт несколько линий - телефон рядом с компьютером, вторая
 * вкладка, - поэтому порог, а не запрет. Обрывать доступ на второй линии
 * значит наказывать за обычное поведение.
 *
 * Считаем в памяти процесса, как и предел по частоте. При выкладке цветов
 * счёт обнуляется; общий счётчик заведён отдельным пунктом работы - здесь
 * важнее сам признак, а не его стойкость к перезапуску.
 */

/** Сколько линий под одним правом ещё похоже на одного человека с устройствами. */
const LINES_PER_VIEWER = 3;

/** Сколько линия живёт без обращений: дольше - это уже другой сеанс. */
const LINE_TTL_MS = 30 * 60 * 1000;

interface Line {
  /** Последнее обращение: по нему линия считается живой. */
  seenAt: number;
  /** Где линия находится в записи - по нему видно, что люди смотрят вразнобой. */
  period: number;
}

const byGrant = new Map<string, Map<string, Line>>();

export interface SharingReport {
  /** Сколько живых линий под этим правом, включая текущую. */
  readonly lines: number;
  /** Линий больше, чем бывает у одного человека. */
  readonly shared: boolean;
  /**
   * Линии стоят в разных местах записи.
   *
   * @remarks
   * Две вкладки одного человека обычно идут рядом; расхождение в несколько
   * криптопериодов означает, что смотрят разное.
   */
  readonly apart: boolean;
}

/**
 * Отмечает обращение за ключом и говорит, на что это похоже.
 *
 * @param grant - право, по которому выдан ключ: идентичность зрителя или учётная запись.
 * @param client - чем различаем обратившихся: адрес или иной признак клиента.
 * @param period - номер криптопериода, который просят.
 */
export function noteKeyRequest(
  grant: string,
  client: string,
  period: number,
  now: number = Date.now(),
): SharingReport {
  const lines = byGrant.get(grant) ?? new Map<string, Line>();
  byGrant.set(grant, lines);

  // Забытые линии убираем при каждом обращении: отдельная уборка по таймеру
  // ради этого не нужна, а карта иначе растёт до перезапуска.
  for (const [key, line] of lines) {
    if (now - line.seenAt > LINE_TTL_MS) lines.delete(key);
  }

  lines.set(client, { seenAt: now, period });

  const places = [...lines.values()].map((line) => line.period);
  const spread = places.length > 1 ? Math.max(...places) - Math.min(...places) : 0;

  return {
    lines: lines.size,
    shared: lines.size > LINES_PER_VIEWER,
    apart: spread > LINES_PER_VIEWER,
  };
}

/** Только для тестов: очищает счёт между проверками. */
export function resetSharedAccess(): void {
  byGrant.clear();
}
