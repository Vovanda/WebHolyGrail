/**
 * Токен зрителя из заголовка кук.
 *
 * @remarks
 * Отдельной вещью, потому что на этом уже обожглись: разбор жил выражением,
 * собранным в шаблонной строке, где `\s` теряет косую черту и превращается
 * в букву `s`. Выражение читало куку только первой в заголовке — стоило
 * браузеру поставить перед ней свою, и идентичность пропадало. Права при этом
 * лежали в базе, но не находились: выданный доступ выглядел как «войдите».
 *
 * Разбор по кускам вместо выражения: у заголовка кук формат простой, и городить
 * над ним регулярное выражение незачем.
 */

/** Имя куки с токеном зрителя. */
export const VIEWER_COOKIE = 'whg-viewer';

export function tokenFromCookieHeader(raw: string, name = VIEWER_COOKIE): string | null {
  for (const part of raw.split(';')) {
    const trimmed = part.trim();
    const eq = trimmed.indexOf('=');
    if (eq < 1) continue;
    // Значение берётся до конца куска: в токене есть точки и дефисы, а знак
    // равенства в нём не встречается - но резать по первому всё равно нельзя,
    // иначе base64 с хвостовым `=` потерял бы конец.
    if (trimmed.slice(0, eq) === name) return trimmed.slice(eq + 1) || null;
  }
  return null;
}
