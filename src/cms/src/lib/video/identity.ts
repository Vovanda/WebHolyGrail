/**
 * Опознание зрителя: телефон, почта или учётная запись.
 *
 * @remarks
 * Доступ принадлежит человеку, а не браузеру, и опознаётся по тому, что тот
 * оставил при покупке. Поэтому номер и адрес обязаны приводиться к единому
 * виду: человек пишет их как придётся, и без приведения тот же телефон не
 * совпадёт сам с собой при возврате с другого устройства.
 */

/**
 * Приводит номер к виду для сравнения: только цифры, российская восьмёрка
 * заменяется семёркой.
 *
 * @remarks
 * `+7 (912) 345-67-89`, `8 912 345 67 89` и `79123456789` — один и тот же
 * человек. Возвращает пустую строку, если на номер это не похоже: пускать
 * мусор в поиск по владельцу нельзя, иначе доступ найдётся не тому.
 */
export function normalizePhone(value: string): string {
  const digits = value.replace(/\D/g, '');
  if (digits.length < 10) return '';

  // Российские номера пишут и с восьмёркой, и с семёркой, и без кода страны.
  if (digits.length === 11 && digits.startsWith('8')) return `7${digits.slice(1)}`;
  if (digits.length === 10) return `7${digits}`;
  return digits;
}

/** Приводит почту к виду для сравнения: регистр и пробелы. */
export function normalizeEmail(value: string): string {
  const email = value.trim().toLowerCase();
  // Минимальная проверка формы: искать доступ по строке без собаки бессмысленно.
  return /^[^@\s]+@[^@\s]+\.[^@\s]+$/.test(email) ? email : '';
}
