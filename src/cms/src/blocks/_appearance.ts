import { APPEARANCE_WARNING } from 'contracts';
import type { Block, Field } from 'payload';

import { VISIBILITY_FIELDS } from './_visibility';

/**
 * Свой стиль блока - одним полем.
 *
 * @remarks
 * Владелец пишет обычный CSS: отступы, скругление любого угла, правила для
 * того, что лежит внутри. Ограничение ровно одно - написанное действует на сам
 * блок и на его содержимое, до остальной страницы не достаёт.
 *
 * Полей нарочно одно, а не пять: подобрать 40 точек сверху и 20 снизу проще
 * записью, чем выбором из чужих слов, а один угол - тем более.
 *
 * Поле объявлено здесь один раз и вешается на блок помощником: скопированное
 * в каждый блок, оно рано или поздно разъезжается.
 */
export function appearanceFields(blockType: string): Field[] {
  return [
    {
      name: 'appearanceCss',
      label: 'Свой стиль (CSS)',
      type: 'textarea',
      admin: {
        description: APPEARANCE_WARNING,
        // Части блока едут полю данными, а не текстом: из них рисуется список
        // с копированием селектора - иначе владелец не знает, до чего внутри
        // может дотянуться.
        // Полю нужен вид блока: по нему оно спрашивает у сервера, из чего блок
        // состоит. Список частей читается из кода компонентов, а не отсюда.
        custom: { blockType },
        // Своё поле: свёрнуто по умолчанию, с переключателем «код или поля».
        // Стиль бывает объёмным, и держать его развёрнутым в каждом блоке
        // незачем.
        components: {
          Field: '/admin/components/AppearanceField',
        },
      },
    },
  ];
}

/**
 * Вид блока: где показывать и как выглядит - одной свёрнутой секцией.
 *
 * @remarks
 * Раньше видимость и стиль лежали в конце каждого блока россыпью и повторялись
 * у всех подряд, занимая место в редакторе. Теперь они убраны под общий
 * заголовок, свёрнутый по умолчанию: открывают их редко, а мешали постоянно.
 *
 * Имена полей в базе от этого не меняются - секция только вид.
 */
function blockViewSection(blockType: string): Field {
  return {
    type: 'collapsible',
    label: 'Вид блока',
    admin: { initCollapsed: true },
    fields: [...VISIBILITY_FIELDS, ...appearanceFields(blockType)],
  };
}

/** Помощник: вернёт копию блока с секцией вида в конце. */
export function withAppearance(block: Block): Block {
  return {
    ...block,
    fields: [...block.fields, blockViewSection(block.slug)],
  };
}
