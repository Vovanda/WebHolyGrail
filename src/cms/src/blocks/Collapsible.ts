import type { Block } from 'payload';

/**
 * Collapsible — свёрнутый кусок текста внутри статьи.
 *
 * @remarks
 * Место для выкладки, которая полезна части читателей, но не обязательна:
 * вывод формулы, разбор замера, длинный пример конфига. Цитатой такое не назвать
 * — это не чужие слова; кодом тоже — это рассуждение. Ставить его в общий поток
 * значит заставить всех прочитать то, что нужно каждому пятому.
 *
 * Поэтому кусок сворачивается, но остаётся видимым заголовком: автор говорит,
 * что подробность есть, а читатель решает, разворачивать ли.
 *
 * Внутри — обычный текст редактора, а не одна строка: выкладке нужны абзацы,
 * списки и выделения ничуть не меньше, чем остальной статье.
 */
export const CollapsibleBlock: Block = {
  slug: 'collapsible',
  labels: { singular: 'Свёрнутый текст', plural: 'Свёрнутые тексты' },
  fields: [
    {
      /**
       * Заголовок — единственное, что видно свёрнутым.
       *
       * @remarks
       * Обязателен: без него на странице остаётся безымянный треугольник,
       * и решить, разворачивать ли, читателю нечем.
       */
      name: 'summary',
      label: 'Заголовок',
      type: 'text',
      required: true,
      admin: {
        description:
          'Что видно, пока текст свёрнут. Называйте содержимое: «Как считается вес нарезки», а не «Подробнее».',
      },
    },
    {
      name: 'body',
      label: 'Текст',
      type: 'richText',
      required: true,
    },
    {
      /**
       * Развернуть сразу.
       *
       * @remarks
       * По умолчанию свёрнут — в этом смысл блока. Настройка для случая, когда
       * выкладку хочется показать, но всё же дать её свернуть.
       */
      name: 'openByDefault',
      label: 'Показывать развёрнутым',
      type: 'checkbox',
      defaultValue: false,
      admin: { description: 'Обычно выключено: блок для того и нужен, чтобы текст был свёрнут.' },
    },
  ],
};
