import type { Block, Where } from 'payload';

/**
 * Галерея: набор снимков и записей одним блоком.
 *
 * @remarks
 * Поставить в текст десяток кадров по одному - значит получить столбик
 * во всю ширину и прокрутку на экран. Здесь они идут набором, а как их
 * показать, владелец выбирает сам.
 *
 * Вид - поле блока, а не свойство показа: у компонента переключателя вёрсток
 * быть не может, такой уже убирали у сетки фич. Блок просто отдаёт набор одной
 * из готовых раскладок шаблона.
 *
 * Записи стоят в галерее наравне со снимками: съёмка с объекта идёт вперемешку
 * с фотографиями, и разделять их по разным блокам незачем.
 */
/**
 * В галерею идут снимки и записи - документам тут не место.
 *
 * Объект один на все отрисовки: окно выбора перезапрашивает список, когда
 * фильтр приходит новым объектом.
 */
const PICTURES_AND_RECORDINGS: Where = {
  or: [{ mimeType: { like: 'image/' } }, { mimeType: { like: 'video/' } }],
};

const galleryBlockBase: Block = {
  slug: 'gallery',
  labels: { singular: 'Галерея', plural: 'Галереи' },
  /*
    В тексте статьи блок показан превью - тем, что увидит читатель, а поля
    открываются кнопкой «Изменить». На блоки страницы это не действует.
  */
  admin: { components: { Block: '/editor/attachment-preview#GalleryPreview' } },
  fields: [
    {
      name: 'heading',
      label: 'Заголовок',
      type: 'text',
      admin: { description: 'Не обязательно. Пусто - галерея идёт без заголовка.' },
    },
    /*
      Кадры - одно поле с несколькими файлами, а не список строк «файл и подпись».

      Список строк внутри блока в тексте статьи ломается в самом Payload: окно
      «выбрать из существующих» пересобирает форму блока из устаревшего снимка,
      строка пропадает, а подложка окна остаётся и закрывает редактор
      (payloadcms/payload#15978, #17232). Поле без строк этой ошибке не подвержено,
      и в окне сразу выбирается весь набор.

      Подпись кадра берётся у самого файла: её видно и в ленте, и в медиатеке,
      править её в одном месте проще, чем в каждой галерее.
    */
    {
      name: 'files',
      label: 'Кадры',
      type: 'upload',
      relationTo: 'media',
      hasMany: true,
      required: true,
      minRows: 1,
      filterOptions: PICTURES_AND_RECORDINGS,
      admin: {
        description:
          'Снимки и записи вперемешку, в том порядке, в каком их показывать. Подпись берётся у файла.',
      },
    },
    {
      name: 'view',
      label: 'Вид',
      type: 'select',
      defaultValue: 'tiles',
      options: [
        { label: 'Плиткой по пропорциям', value: 'tiles' },
        { label: 'Каруселью', value: 'carousel' },
        { label: 'Подряд, один под другим', value: 'list' },
      ],
      admin: {
        description:
          'Плитка - когда кадров много и важно показать их разом. Карусель - когда места мало. Подряд - когда каждый кадр стоит рассмотреть.',
      },
    },
  ],
};

/*
  Раскладки плиток у галереи нет: её плитку рисует AspectRows по формам
  снимков, фигура из ячеек к ней не применяется.
*/
export const GalleryBlock: Block = galleryBlockBase;
