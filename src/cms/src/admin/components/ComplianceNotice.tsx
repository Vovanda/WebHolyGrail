import type { Payload } from 'payload';

/**
 * Напоминание владельцу сайта: уведомление в Роскомнадзор ещё не подано.
 *
 * @remarks
 * Висит на главной странице админки, пока в настройках не отмечено «Уведомление
 * подано». Убрать его нельзя, и это осознанно: сайт с формой обратной связи
 * делает владельца оператором персональных данных, а уведомление подаёт он сам
 * — через Госуслуги, за него это не сделает ни разработчик, ни агентство.
 *
 * Разработчик закрывает техническую часть: согласие в форме, политика на сайте,
 * шифрование базы, хранение в России. Подача уведомления остаётся за
 * оператором, поэтому напоминание живёт в его рабочем месте, а не в задачах
 * разработчика.
 */
export async function ComplianceNotice({ payload }: { payload: Payload }) {
  const settings = (await payload
    .findGlobal({ slug: 'site-settings', depth: 0 })
    .catch(() => null)) as { personalData?: { rknNotified?: boolean } } | null;

  if (settings?.personalData?.rknNotified) return null;

  return (
    <div
      style={{
        border: '1px solid var(--theme-warning-500, #d97706)',
        background: 'var(--theme-warning-50, #fffbeb)',
        color: 'var(--theme-elevation-800, #1a1515)',
        borderRadius: '.375rem',
        padding: '1rem 1.25rem',
        marginBottom: '1.5rem',
        lineHeight: 1.55,
      }}
    >
      <strong style={{ display: 'block', marginBottom: '.4rem' }}>
        Уведомление в Роскомнадзор не подано
      </strong>
      <p style={{ margin: '0 0 .6rem' }}>
        На сайте есть форма, которая собирает имя и контакт, — значит владелец сайта считается
        оператором персональных данных и обязан подать уведомление. Это бесплатно и делается через
        Госуслуги примерно за полчаса.
      </p>
      <p style={{ margin: '0 0 .6rem' }}>
        После подачи придёт номер записи в реестре операторов. Впишите его в настройках сайта,
        раздел «Обработка персональных данных», и отметьте галочку — напоминание пропадёт, а номер
        подставится в текст политики.
      </p>
      <p style={{ margin: 0, opacity: 0.85 }}>
        Техническая часть со стороны сайта уже сделана: согласие в форме, политика на отдельной
        странице, данные хранятся в России, база зашифрована.
      </p>
    </div>
  );
}
