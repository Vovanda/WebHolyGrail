import { type MigrateDownArgs, type MigrateUpArgs, sql } from '@payloadcms/db-sqlite';

/*
  Ступени оформления заменены одним полем со своим стилем: владелец пишет CSS,
  а не выбирает из наших слов. Пять колонок уходят, одна приходит.

  Каждая правка идёт по факту: список таблиц у блока свой на каждом сайте -
  он зависит от того, где блок разрешили ставить, - и слепой ALTER TABLE
  завалил бы весь прогон на первой же недостающей таблице, а с ним и выкладку.
*/

async function hasColumn(db: MigrateUpArgs['db'], table: string, column: string) {
  const rows = await db.all(sql.raw(`PRAGMA table_info(\`${table}\`)`));
  return (rows as Array<{ name: string }>).some((row) => row.name === column);
}

async function hasTable(db: MigrateUpArgs['db'], table: string) {
  const rows = await db.all(
    sql.raw(`SELECT name FROM sqlite_master WHERE type='table' AND name='${table}'`),
  );
  return (rows as unknown[]).length > 0;
}

async function dropIfExists(db: MigrateUpArgs['db'], table: string, column: string) {
  if (!(await hasTable(db, table))) return;
  if (!(await hasColumn(db, table, column))) return;
  await db.run(sql.raw(`ALTER TABLE \`${table}\` DROP COLUMN \`${column}\`;`));
}

async function addIfMissing(db: MigrateUpArgs['db'], table: string, column: string) {
  if (!(await hasTable(db, table))) return;
  if (await hasColumn(db, table, column)) return;
  await db.run(sql.raw(`ALTER TABLE \`${table}\` ADD \`${column}\` text;`));
}

