/**
 * Медиа-документ: загруженный файл (картинка / pdf / документ).
 *
 * @remarks
 * Источник правды — коллекция `Media` в Payload (см. cms/collections/Media.ts).
 * Здесь — публичный контракт того что `client` получает в ответ от CMS.
 * Не повторяет внутренние поля Payload (id-схема, timestamps управления) —
 * только то что нужно фронту для рендера.
 */
export interface MediaDoc {
  /**
   * Идентификатор документа в CMS.
   *
   * @remarks
   * Число или строка: у разных баз ключ разный, и запись из SQLite приходит
   * с числовым. Показ его не читает, а тем, кто читает, приведение достаётся
   * задаром - но тип обязан говорить правду, иначе соседний шов расходится
   * с этим на ровном месте.
   */
  readonly id: string | number;
  /** Публичный URL для отдачи (CDN или путь относительно сайта). */
  readonly url: string;
  /**
   * Альтернативный текст.
   *
   * @remarks
   * Заполнять его надо всегда - это доступность и поисковая выдача, - но
   * обязательным в типе он быть не может: записи заводились и до того, как
   * поле появилось, а показ к пустому готов и берёт подпись у блока.
   */
  readonly alt?: string;
  /**
   * Название файла для человека.
   *
   * @remarks
   * Показывается под кадром, когда его открыли крупно. Не путать с `alt`:
   * тот описывает изображение тем, кто его не видит, и в поиске читается
   * машиной, а это - заголовок, который читает зритель.
   */
  readonly caption?: string | null;
  /** Пояснение к файлу: показывается под кадром и уходит в поисковую выдачу. */
  readonly description?: string | null;
  /**
   * Размытая заготовка кадра строкой.
   *
   * @remarks
   * Показывается на месте снимка, пока он идёт по сети. Приходит вместе
   * с данными страницы, своего запроса не делает. У файлов, залитых до
   * появления заготовок, её нет.
   */
  readonly blurData?: string | null;
  /** Ширина изображения в пикселях (если применимо). */
  readonly width?: number;
  /** Высота изображения в пикселях (если применимо). */
  readonly height?: number;
  /** MIME-тип файла, напр. `image/jpeg`, `application/pdf`. */
  readonly mimeType?: string;
  /** Размер файла в байтах. */
  readonly filesize?: number;
  /** Производные размеры (превью, разные брейкпоинты). Ключ — имя варианта. */
  readonly sizes?: Readonly<Record<string, MediaSize>>;
  /** Нарезка записи: есть только у видео и только после подготовки. */
  readonly hls?: MediaStream;
  /**
   * Кадр из записи: снимается при подготовке видео.
   *
   * @remarks
   * Лежит адресом рядом с записью, а не связью: списки грузят записи без
   * вложенности, и по связи адрес там не достать.
   */
  readonly previewUrl?: string | null;
  /**
   * Тот же кадр записи документом медиатеки.
   *
   * @remarks
   * Адреса мало: из строки не узнать ни ступеней нарезки, ни формы кадра, ни
   * заготовки, и место с ним тянет полный кадр в плитку размером с ладонь.
   * Документ приходит раскрытым там, где запрос идёт с вложенностью; в списках
   * на его месте номер, и тогда показ остаётся на адресе.
   */
  readonly preview?: MediaRef | null;
  /**
   * Точка, вокруг которой кадр подрезается.
   *
   * @remarks
   * Задаётся владельцем в админке и хранится долями ширины и высоты, от нуля
   * до ста. Там, где кадр заполняет отведённое место, подрезка идёт вокруг неё:
   * без этого узкий снимок теряет то, ради чего его и сняли.
   */
  readonly focalX?: number | null;
  readonly focalY?: number | null;
  /**
   * Предел ступени на странице.
   *
   * @remarks
   * Размер под место показ выбирает сам, но про сам снимок владелец знает
   * больше: у общего плана мелкая ступень читается так же, а весит втрое
   * меньше. Имя ступени здесь ограничивает набор сверху; пусто - решает место.
   */
  readonly pageStep?: MediaRenditionName | null;
  /**
   * Предел ступени при открытии на весь экран.
   *
   * @remarks
   * Отдельно от страницы: в потоке кадр может идти мелким, а рассматривают его
   * крупным - и наоборот, тяжёлый скан незачем тянуть целиком даже в ленте.
   */
  readonly laneStep?: MediaRenditionName | null;
}

/**
 * Нарезка записи: то, чем её играет плеер.
 *
 * @remarks
 * Загруженный файл остаётся в хранилище, но браузеру отдаётся не он, а
 * манифест: тот приходит кусками, поэтому первый кадр появляется, не дожидаясь
 * всей записи, и с него же можно начать с любого места.
 *
 * Адрес манифеста ведёт на дверь самого сайта, а не в хранилище (R15): внутри
 * манифеста стоит путь ключа, и браузер разрешает его от адреса манифеста.
 *
 * Готовность отдельным полем: нарезка идёт в фоне, и до её конца играть нечего -
 * тому, кто показывает запись, нужно отличить «ещё режется» от «сломалось».
 */
export interface MediaStream {
  /** Готова ли запись к показу. */
  readonly status?: 'pending' | 'processing' | 'ready' | 'failed';
  /** Адрес манифеста на своём домене. */
  readonly playlistUrl?: string | null;
  /** Длительность записи в секундах. */
  readonly durationSeconds?: number | null;
}

/**
 * Ступень нарезки картинки: адрес и размеры.
 *
 * @remarks
 * Имена и ширины ступеней задаёт `MEDIA_RENDITIONS`; по нему же режет CMS.
 */
export interface MediaSize {
  readonly url: string;
  readonly width: number;
  readonly height: number;
}

/**
 * Минимальная ссылка на медиа в полях документов: либо строка-id, либо populated объект.
 *
 * @remarks
 * Payload по умолчанию возвращает `id` если глубина запроса 0, и объект если ≥ 1.
 * Контракт допускает оба варианта — `client` должен уметь обрабатывать.
 */
export type MediaRef = string | MediaDoc;

/**
 * Ступени нарезки картинок: по ним CMS режет варианты, а сайт их просит.
 *
 * @remarks
 * Список живёт в шве и объявлен значением, а не только типом: по нему строится
 * и нарезка в коллекции медиа, и пороги выбора на стороне сайта. Объяви его
 * дважды - и однажды сайт попросит ступень, которой никто не режет.
 *
 * Шаг подобран так, чтобы между соседними не было провала: на разрыве
 * 768 - 1920 браузер честно тянул полуторамегабайтный кадр в колонку шириной
 * 830 точек.
 */
export const MEDIA_RENDITIONS = [
  { name: 'thumbnail', width: 400 },
  { name: 'card', width: 768 },
  { name: 'wide', width: 1200 },
  { name: 'hero', width: 1920 },
  { name: 'full', width: 2560 },
] as const;

/** Имя ступени нарезки. */
export type MediaRenditionName = (typeof MEDIA_RENDITIONS)[number]['name'];

/** Форма места под кадр: ширина к высоте. */
export interface FrameAspect {
  readonly width: number;
  readonly height: number;
}

const LANDSCAPE: FrameAspect = { width: 16, height: 9 };
const PORTRAIT: FrameAspect = { width: 9, height: 16 };

/**
 * Форма одиночного кадра в тексте: 16:9 или 9:16 по ориентации снимка.
 *
 * @remarks
 * Снимки в статье приходят какой угодно формы, и столбик из них выглядит
 * случайным. Две формы на всё дают ровный ритм, а подрезка идёт вокруг точки,
 * выбранной владельцем. Квадрат идёт лёжа: стоячая форма у него съела бы
 * больше, чем лежачая. Без размеров формы нет - кадр идёт как есть.
 *
 * Правило одно на сайт и на редактор статьи: в редакторе кадр показан той же
 * формой, что увидит читатель.
 */
export function frameAspectOf(
  size: { readonly width?: number | null; readonly height?: number | null } | null | undefined,
): FrameAspect | undefined {
  if (!size?.width || !size.height) return undefined;
  return size.height > size.width ? PORTRAIT : LANDSCAPE;
}

/**
 * Тип файла словом: «PDF», «изображение», «видео».
 *
 * @remarks
 * Стоит в карточке документа на сайте и в его превью в редакторе - слово одно
 * и то же в обоих местах.
 */
export function fileKindOf(mime: string | null | undefined): string {
  if (!mime) return 'файл';
  if (mime === 'application/pdf') return 'PDF';
  if (mime.startsWith('image/')) return 'изображение';
  if (mime.startsWith('video/')) return 'видео';
  return mime.split('/').pop() || 'файл';
}
